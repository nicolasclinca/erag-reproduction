def _parse_relevance(raw_rel: Any) -> Any:
    """
    Robust parsing:
    - float(raw_rel) if possible
    - if nearly integer -> int (codebase style)
    - fallback 0
    """
    try:
        rel_val: Any = float(raw_rel)
        if abs(rel_val - round(rel_val)) < 1e-12:
            rel_val = int(round(rel_val))
        return rel_val
    except Exception:
        return 0


def list_assessed_run_files(folder: str) -> List[str]:
    files: List[str] = []
    if not os.path.isdir(folder):
        return files
    for name in os.listdir(folder):
        p = os.path.join(folder, name)
        if not os.path.isfile(p):
            continue
        if name.lower().endswith("_assessed_run.csv"):
            files.append(p)
    return sorted(files)


def load_positive_qrels_map(qrels_path: str) -> Dict[Tuple[str, str], Any]:
    """
    Load an existing <dataset>_all_qrels.csv and return:
      (query_id, doc_id) -> relevance

    Note: we expect only relevance > 0, but we do robust parsing and keep max on duplicates.
    """
    rel_map: Dict[Tuple[str, str], Any] = {}

    with open(qrels_path, "r", encoding="utf-8", newline="") as f:
        r = csv.DictReader(f)
        for row in r:
            qid = str(row.get("query_id", "")).strip()
            did = str(row.get("doc_id", "")).strip()
            if not qid or not did:
                continue

            rel_val = _parse_relevance(row.get("relevance", 0))
            try:
                rel_f = float(rel_val)
            except Exception:
                rel_f = 0.0

            if rel_f <= 0.0:
                continue

            key = (qid, did)
            if key in rel_map:
                try:
                    prev = float(rel_map[key])
                    cur = float(rel_val)
                    rel_map[key] = rel_val if cur > prev else rel_map[key]
                except Exception:
                    rel_map[key] = rel_val
            else:
                rel_map[key] = rel_val

    return rel_map


def load_assessed_runs_cache(folder: str) -> Tuple[Set[Tuple[str, str]], Dict[Tuple[str, str], Any], int]:
    """
    Scan *_assessed_run.csv in folder and return:
      - evaluated_pairs: set((query_id, doc_id)) for ALL rows (includes relevance=0)
      - positive_rel_map: (qid,did)->relevance ONLY for relevance>0 (max on duplicates)
      - files_count
    """
    evaluated_pairs: Set[Tuple[str, str]] = set()
    positive_rel_map: Dict[Tuple[str, str], Any] = {}

    files = list_assessed_run_files(folder)
    for p in files:
        with open(p, "r", encoding="utf-8", newline="") as f:
            r = csv.DictReader(f)
            if not r.fieldnames:
                continue

            needed = {"query_id", "doc_id", "relevance"}
            if not needed.issubset(set(r.fieldnames)):
                continue

            for row in r:
                qid = str(row.get("query_id", "")).strip()
                did = str(row.get("doc_id", "")).strip()
                if not qid or not did:
                    continue

                key = (qid, did)
                evaluated_pairs.add(key)

                rel_val = _parse_relevance(row.get("relevance", 0))
                try:
                    rel_f = float(rel_val)
                except Exception:
                    rel_f = 0.0

                if rel_f <= 0.0:
                    continue

                if key in positive_rel_map:
                    try:
                        prev = float(positive_rel_map[key])
                        cur = float(rel_val)
                        positive_rel_map[key] = rel_val if cur > prev else positive_rel_map[key]
                    except Exception:
                        positive_rel_map[key] = rel_val
                else:
                    positive_rel_map[key] = rel_val

    return evaluated_pairs, positive_rel_map, len(files)


