"""
build_all_erag_qrels.py

Given a <dataset>_all_runs.csv file (query_id, doc_id), compute the “model-based” eRAG qrels
for ALL (query_id, doc_id) pairs present, using a FiD-T5 model.

Default experiment layout
-------------------------
By default, this script assumes an experiment folder structure:

  <exp_root>/<dataset>/
    all-runs/        <dataset>_all_runs.csv
    all-qrels/       <dataset>_all_qrels.csv
    assessed-runs/   *_assessed_run.csv

Output
------
Writes <dataset>_all_qrels.csv with header:
  query_id, doc_id, relevance

and includes ONLY rows with relevance > 0.

Cache / incremental
-------------------
To avoid evaluating the same (query_id, doc_id) pair twice, it uses as cache:

1) Any <dataset>_all_qrels.csv file already present in the all-qrels folder
   (contains only relevance > 0).

2) Any *_assessed_run.csv files present in the assessed-runs folder (generated by
   build_all_assessed_runs.py), which also contain relevance = 0.

The “assessed_run” cache makes it possible to avoid recomputing even pairs already evaluated
with relevance = 0 (which do not appear in <dataset>_all_qrels.csv).

Note
----
Here we do NOT compute IR metrics (P@k, nDCG, etc.): we just need to generate the answer using
only that document as context and compute the downstream_metric (EM/Accuracy/F1),
which corresponds to the relevance to log.

Required inputs
---------------
- --all_runs: CSV with columns query_id, doc_id (any extra columns are ignored)
- --datasets: one or more KILT .jsonl files (for query_text and gold answers)
- --collection: JSONL document collection (id, contents)
- --model_dir: FiD-T5 model directory

CLI usage
-------
python build_all_erag_qrels.py \
  --exp_root ../exp-output \
  --dataset nq \
  --datasets ../data/nq-dev-kilt.jsonl \
  --collection ../data/collection/wikipedia_passages.jsonl \
  --model_dir ../models/fid_t5 \
  --metric em \
  --overwrite

Custom all_runs / output:
python build_all_erag_qrels.py \
  --all_runs ../exp-output/nq/all-runs/nq_all_runs.csv \
  --output  ../exp-output/nq/all-qrels/nq_all_qrels.csv \
  --datasets ../data/nq-dev-kilt.jsonl \
  --collection ../data/collection/wikipedia_passages.jsonl \
  --model_dir ../models/fid_t5 \
  --metric em \
  --overwrite
"""

