def format_relevance(score: float, score_precision: int = 6) -> Any:
    """
    Format relevance as in build_erag_qrels.py:
    - int if it's “nearly integer” (EM/accuracy)
    - otherwise a formatted float
    """
    try:
        s = float(score)
    except Exception:
        s = 0.0

    if abs(s - round(s)) < 1e-12:
        return int(round(s))

    fmt = f"{{:.{int(score_precision)}f}}"
    return float(fmt.format(s))


# -----------------------------
# Core: compute and write qrels (only relevance > 0), reusing cache
# -----------------------------
def write_all_erag_qrels_csv(
    pairs_by_qid: Dict[str, List[str]],
    query_id_to_query: Dict[str, str],
    doc_id_to_document: Dict[str, str],
    expected_outputs: Dict[str, List[str]],
    text_generator,
    downstream_metric_func,
    out_path: str,
    *,
    score_precision: int = 6,
    evaluated_pairs: Optional[Set[Tuple[str, str]]] = None,
    cached_positive_rel_map: Optional[Dict[Tuple[str, str], Any]] = None,
) -> None:
    """
    Run generation+metrics for each (qid, docid) pair in pairs_by_qid,
    skipping pairs present in evaluated_pairs (cache) and writing:

    - all cached pairs with relevance > 0 (cached_positive_rel_map)
    - all new pairs with relevance > 0

    Note:
    - evaluated_pairs is used to avoid recomputing pairs already evaluated with relevance=0 as well.
    - cached_positive_rel_map is only used to immediately write already-known positives.
    """
    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    tmp_path = out_path + ".tmp"

    evaluated_pairs = evaluated_pairs or set()
    cached_positive_rel_map = cached_positive_rel_map or {}

    qids = list(pairs_by_qid.keys())
    max_len = max((len(lst) for lst in pairs_by_qid.values()), default=0)

    with open(tmp_path, "w", encoding="utf-8", newline="") as f_out:
        w = csv.writer(f_out)
        w.writerow(["query_id", "doc_id", "relevance"])

        # 1) write cached positives first
        cached_written = 0
        for (qid, did), rel in cached_positive_rel_map.items():
            try:
                rel_f = float(rel)
            except Exception:
                rel_f = 0.0
            if rel_f <= 0.0:
                continue
            w.writerow([qid, did, format_relevance(rel_f, score_precision=score_precision)])
            cached_written += 1

        written_new = 0
        processed_new = 0

        for i in range(max_len):
            # items: (qid, qtext, doc_id, doc_text)
            items: List[Tuple[str, str, str, str]] = []
            for qid in qids:
                doc_ids = pairs_by_qid.get(qid, []) or []
                if i >= len(doc_ids):
                    continue

                doc_id = str(doc_ids[i])
                key = (qid, doc_id)

                # cache hit: skip compute (includes relevance=0 already evaluated)
                if key in evaluated_pairs:
                    continue

                if qid not in query_id_to_query:
                    raise KeyError(f"query_id_to_query missing query_id: {qid}")

                qtext = query_id_to_query[qid]
                dtext = doc_id_to_document.get(doc_id, "")

                items.append((qid, qtext, doc_id, dtext))

            if not items:
                continue

            # Batch only on unique query_text; duplicates -> one-by-one
            qtext_counts = Counter(qtext for (_qid, qtext, _did, _dtext) in items)

            batch_input: Dict[str, List[str]] = {}
            batch_expected: Dict[str, List[str]] = {}
            backmap: List[Tuple[str, str, str]] = []  # (qid, qtext, doc_id)
            dup_items: List[Tuple[str, str, str, str]] = []

            for qid, qtext, doc_id, doc_text in items:
                if qtext_counts[qtext] == 1:
                    batch_input[qtext] = [doc_text]
                    batch_expected[qtext] = expected_outputs.get(qid, []) or []
                    backmap.append((qid, qtext, doc_id))
                else:
                    dup_items.append((qid, qtext, doc_id, doc_text))

            # --- Batch part ---
            if batch_input:
                generated = text_generator(batch_input)
                if set(generated.keys()) != set(batch_input.keys()):
                    raise RuntimeError("The text_generator function did not return outputs for all given inputs.")

                scores = downstream_metric_func(generated, batch_expected)
                if set(scores.keys()) != set(generated.keys()):
                    raise RuntimeError(
                        "The downstream_metric function did not return evaluation scores for all given inputs."
                    )

                for qid, qtext, doc_id in backmap:
                    processed_new += 1
                    s = float(scores.get(qtext, 0.0))
                    if s > 0.0:
                        w.writerow([qid, doc_id, format_relevance(s, score_precision=score_precision)])
                        written_new += 1

            # --- Duplicate query_text in same batch: one-by-one ---
            for qid, qtext, doc_id, doc_text in dup_items:
                generated = text_generator({qtext: [doc_text]})
                if qtext not in generated:
                    raise RuntimeError("The text_generator function did not return outputs for all given inputs.")
                scores = downstream_metric_func(generated, {qtext: expected_outputs.get(qid, []) or []})
                if qtext not in scores:
                    raise RuntimeError(
                        "The downstream_metric function did not return evaluation scores for all given inputs."
                    )

                processed_new += 1
                s = float(scores.get(qtext, 0.0))
                if s > 0.0:
                    w.writerow([qid, doc_id, format_relevance(s, score_precision=score_precision)])
                    written_new += 1

            if (i + 1) % 10 == 0:
                print(
                    f"Processed rank-position i={i+1}/{max_len}. "
                    f"New pairs processed so far: {processed_new}, new written: {written_new}, cached written: {cached_written}"
                )

        print(
            f"Done. New pairs processed: {processed_new}, new written (relevance>0): {written_new}, "
            f"cached written: {cached_written}"
        )

    os.replace(tmp_path, out_path)
    print(f"Saved qrels -> {out_path}")


